const assert=require('node:assert/strict');
const C=require('../app/src/main/assets/config.js');
const E=require('../app/src/main/assets/engine.js');
const good={fee:.03,slip:.005,borrow:.001,funding:-.002,liq:90};
for(const bad of [{...good,fee:NaN},{...good,fee:-1},{...good,slip:100},{...good,borrow:-1},{...good,liq:0},{...good,liq:101}])assert.throws(()=>E.open(0,true,10,10,100,bad));
assert.throws(()=>E.open(0,true,10,.5,100,good));
assert.throws(()=>E.open(0,'false',10,10,100,good));
assert(E.freshQuote(100,9999,10000));
assert(!E.freshQuote(100,10001,10000));
assert(!E.freshQuote(100,5000,10000));
assert(!E.freshQuote(Infinity,9999,10000));
assert(!E.freshQuote(100,0,10000));
assert.deepEqual(E.dedupeCandles([{t:60000,o:1,h:1,l:1,c:NaN}]),[]);
assert.deepEqual(E.dedupeCandles([{t:60000,o:5,h:2,l:1,c:4}]),[]);
assert.deepEqual(E.dedupeCandles([{t:60001,o:1,h:2,l:1,c:2}]).map(x=>x.t),[60000]);
C.discover([{pairIndex:0,symbol:'BTC/USD',maxLeverage:50,group:'crypto'},{pairIndex:22,symbol:'USD/JPY',maxLeverage:100,group:'forex'}]);
assert.equal(C.market(0).maxLeverage,50);
assert.equal(C.allMarkets().filter(m=>m.pairIndex===0).length,1);
assert.equal(C.apiSymbol(C.market(22)),'USD-JPY');
assert.throws(()=>E.open(0,true,10,51,100,good));
C.discover([{pairIndex:0,symbol:'BTC/USD',maxLeverage:0,group:'crypto'}]);
assert.throws(()=>C.market(0),/unavailable/);
assert.throws(()=>E.open(0,true,10,1,100,good));
console.log('PASS: cost invariants, future/stale quotes, singleton candles, changing market caps, disabled markets and forex symbols.');
